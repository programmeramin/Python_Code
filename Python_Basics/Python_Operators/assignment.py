# 📝 4️⃣ Assignment Operators
# ভ্যারিয়েবলে value assign করার জন্য
# =
# +=
# -=
# *=
# /=
# %=
# **=
# //=


a = 23
b = 34


#= 

a += 10
print(a) # 33

b -= 10
print(b)  # 23

a *= 10
print(a) # 230

c = 56
c /= 5
print(c) # 11.0

x = 10
x %= 4
print(x) # 2

x = 2
x **= 3   # x = x ** 3
print(x)   # 8


x = 10
x //= 3   # x = x // 3
print(x)   # 3
