# 2️⃣ Comparison (Relational) Operators
# == (Equal)
# != (Not equal)
# > (Greater than)
# < (Less than)
# >= (Greater equal)
# <= (Less equal)

a = 10 
b = 12
if a == b:
  print("A & B equal")  

if a != b:
  print("A & B not equal")

if a > b: 
  print("A greater than B")

if a < b:
  print("A less than B")

if a >= b:
  print("A Greater or equal B")

if a <= b:
  print("A Less or equal B")  
